def _sparkline(values: list[float], width: float = 150, height: float = 28) -> Drawing:
    d = Drawing(width, height)
    if len(values) < 2:
        return d
    lo, hi = min(values), max(values)
    span = (hi - lo) or 1.0
    n = len(values)
    pts: list[float] = []
    for i, v in enumerate(values):
        x = (i / (n - 1)) * (width - 4) + 2
        y = 2 + ((v - lo) / span) * (height - 4)
        pts.extend([x, y])
    d.add(Line(0, 2, width, 2, strokeColor=colors.HexColor("#dee2e6"), strokeWidth=0.5))
    d.add(PolyLine(pts, strokeColor=_WOLF, strokeWidth=1.5))
    return d


def _header_footer(lang: str, edition: str):
    t = _T[lang]
    ts = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

    def draw(canvas, doc):
        canvas.saveState()
        # Encabezado: marca Wolf (texto, sin asset de logo).
        canvas.setFillColor(_WOLF)
        canvas.setFont("Helvetica-Bold", 13)
        canvas.drawString(18 * mm, A4[1] - 15 * mm, "\U0001f43a  Wolf DevSecOps")
        canvas.setStrokeColor(_WOLF)
        canvas.setLineWidth(0.8)
        canvas.line(18 * mm, A4[1] - 17 * mm, A4[0] - 18 * mm, A4[1] - 17 * mm)
        # Pie: bloque de firma estándar + número de página.
        canvas.setFillColor(colors.HexColor("#868e96"))
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(18 * mm, 12 * mm, t["sign"])
        canvas.drawRightString(
            A4[0] - 18 * mm, 8 * mm,
            t["footer"].format(ed=edition, ts=ts, p=canvas.getPageNumber()),
        )
        canvas.restoreState()

    return draw


def build_pdf(
    summary: ProjectSummary,
    history: list[PostureSnapshot],
    accepted: list[IgnoreEntry],
    *,
    lang: str = "es",
    edition: str = "community",
) -> bytes:
    """Arma el PDF de cumplimiento del proyecto y devuelve sus bytes."""
    lang = "en" if lang == "en" else "es"
    t = _T[lang]
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Heading1"], textColor=_WOLF, fontSize=16, spaceAfter=6)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=_WOLF, fontSize=12, spaceBefore=12)
    body = styles["BodyText"]
    small = ParagraphStyle("small", parent=body, fontSize=8, textColor=colors.HexColor("#495057"))

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, title=f"{t['title']} — {summary.name}",
        topMargin=22 * mm, bottomMargin=20 * mm, leftMargin=18 * mm, rightMargin=18 * mm,
    )
    story: list = []
    story.append(Paragraph(t["title"], h1))
    story.append(Paragraph(f"<b>{t['project']}:</b> {summary.name} ({summary.key})", body))
    story.append(Paragraph(f"<b>{t['org']}:</b> {summary.org}", body))
    story.append(Paragraph(
        f"<b>{t['generated']}:</b> {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}", small))

    posture = summary.posture
    if posture is None or posture.score is None:
        story.append(Spacer(1, 8))
        story.append(Paragraph(t["nodata"], body))
    else:
        story.append(Spacer(1, 6))
        score_tbl = Table(
            [[f"{t['score']}", f"{t['coverage']}", f"{t['band']}"],
             [f"{posture.score}%", f"{posture.coverage}%", str(posture.band)]],
            colWidths=[55 * mm, 55 * mm, 60 * mm],
        )
        score_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e7f5ff")),
            ("TEXTCOLOR", (0, 0), (-1, 0), _WOLF),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 1), (-1, 1), 14),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#ced4da")),
            ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(score_tbl)

        # Tendencia.
        story.append(Paragraph(t["trend"], h2))
        series = [s.compliance_pct for s in history]
        if len(series) >= 2:
            story.append(_sparkline(series))
            delta = series[-1] - series[0]
            story.append(Paragraph(
                t["trend_delta"].format(d=f"{delta:+.1f}", n=len(series)), small))
        else:
            story.append(Paragraph(t["trend_none"], small))

        # Checks + mapeo.
        story.append(Paragraph(t["checks"], h2))
        rows = [[t["check"], t["result"], t["earned"], t["weight"]]]
        for c in posture.checks:
            earned = c.earned if c.earned != int(c.earned) else int(c.earned)
            rows.append([c.id, t["outcome"].get(c.result, c.result),
                         "—" if c.result == "na" else str(earned), str(c.weight)])
        ctbl = Table(rows, colWidths=[62 * mm, 40 * mm, 30 * mm, 30 * mm])
        cstyle = [
            ("BACKGROUND", (0, 0), (-1, 0), _WOLF), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#ced4da")),
            ("ALIGN", (2, 0), (-1, -1), "RIGHT"),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8f9fa")]),
        ]
        for i, c in enumerate(posture.checks, start=1):
            cstyle.append(("TEXTCOLOR", (1, i), (1, i), _OUTCOME_COLOR.get(c.result, colors.black)))
        ctbl.setStyle(TableStyle(cstyle))
        story.append(ctbl)

        story.append(Paragraph(t["mapping"], h2))
        mrows = [[t["check"], "ISO/IEC 27001:2022", "NIST SSDF", "OWASP DSOMM"]]
        for c in posture.checks:
            m = COMPLIANCE_MAP.get(c.id, {})
            mrows.append([c.id, m.get("iso", "—"), m.get("ssdf", "—"), m.get("dsomm", "—")])
        mtbl = Table(mrows, colWidths=[52 * mm, 40 * mm, 30 * mm, 40 * mm])
        mtbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), _WOLF), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#ced4da")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8f9fa")]),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(mtbl)

    # Riesgos aceptados (6.3.d).
    story.append(Paragraph(t["accepted"], h2))
    if not accepted:
        story.append(Paragraph(t["accepted_none"], small))
    else:
        arows = [[t["ac_id"], t["ac_reason"], t["ac_by"], t["ac_exp"]]]
        for e in accepted:
            # reason es dato del usuario → escapar antes de Paragraph (mini-markup de reportlab).
            arows.append([e.match, Paragraph(escape(e.reason or "—"), small), e.approved_by or "—", e.expires or "—"])
        atbl = Table(arows, colWidths=[40 * mm, 72 * mm, 30 * mm, 20 * mm])
        atbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8590c")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#ced4da")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(atbl)

    hf = _header_footer(lang, edition)
    doc.build(story, onFirstPage=hf, onLaterPages=hf)
    return buf.getvalue()
